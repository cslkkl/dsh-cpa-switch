/**
 * 展示用的格式化。
 *
 * 与传输层分开的理由只有一条：**它不是传输** —— 一个把数字变成人看的样子
 * 的函数待在「发请求」的文件里，下次找格式化规则的人不会想到去那里翻。
 *
 * ## 大数缩写（2026-10-25 维护者定案）
 *
 * | 值              | 结果        | 为什么                                   |
 * | --------------- | ----------- | ---------------------------------------- |
 * | `508_000_000`   | `508M`      | 百万起换一档，**只到 M**                 |
 * | `5_080_000_000` | `5,080M`    | **不上 B** —— 同屏两档反而更难比大小     |
 * | `999_999`       | `999,999`   | `< 1e6` 保持原样，千分位照旧             |
 * | `0`             | `0`         | 0 由 `amountWithUnit` 判成「不带单位」   |
 * | 缺失 / 非有限数 | `—`         | 上游没给这个数                           |
 *
 * ⚠️ **缩写只由「数值量级」决定，与单位无关** —— 这一层**不许**按单位分支
 * （不要拿单位字符串去比，也不要认识 `CreditUnit`）。单位的每一种判定都只有一处
 * （`credit-text.ts`），`tests/credit-text.test.ts` 有一条判据扫全仓「判 token」
 * 的写法（连注释里出现都算），在这里写第二处会被当场判红。
 *
 * ⚠️ **「值 + 单位 → 最终字符串」仍然只有 `amountWithUnit` 一处**
 * （`meter-text.ts`，含「0 不带单位」那条规则）。本文件只负责把**数字**变成
 * 带 `M` 的字符串，单位由 `amountWithUnit` 拼 —— 所以 `M` 会落在数字那一半，
 * 汇总三格按 `' ' + unit` 拆节点的做法照旧成立（`508M token` 照样拆得开）。
 *
 * ⚠️ **百万这个常数全仓只有这一处**（`1e6`）。判据
 * `tests/format.test.ts` 扫 `src/client/**`：除本文件外出现 `1e6` / `1000000` /
 * `1_000_000` 即判红 —— 那正是「第二份缩写实现」长回来的样子，而它在界面上
 * 表现为**同一屏两种写法**（卡片 `508M`、汇总 `508,000,000`），不报错。
 *
 * @module dsh-cpa-switch/client/format
 */

/**
 * 百万那一档 —— **整个仓只此一处**（见文件头注的守卫判据）。
 *
 * 用 `Math.abs` 比：上游偶尔用负数表示「无限」（`-1`），
 * 写成 `value < MEGA` 会让 `-5_000_000` 走进「小于百万」那一支、
 * 原样印成 `-5,000,000`，与正数那种写法分家。
 */
const MEGA = 1e6

/**
 * 数字 → 界面上的那串数字（千分位；百万起缩写为 `M` 档）。
 *
 * 只管**数字**：单位与「0 不带单位」由 `amountWithUnit` 拼（见文件头注）。
 *
 * @param value - 数值；非数值 / 非有限数 → `—`（与缺失同一口径，不编 0）。
 * @returns 千分位串，或百万起的缩写串（`508M` / `5,080M`）。
 */
export function fmt(value: unknown): string {
  if (typeof value !== 'number' || !Number.isFinite(value)) return '—'
  // 小于一百万：原样千分位 —— `999,999` 与 `1,234` 都不缩写
  if (Math.abs(value) < MEGA) return value.toLocaleString('en-US')
  /**
   * 百万起：除以一百万，最多两位小数。
   *
   * 保留两位而不是取整：`1_234_567` 取整会变成 `1M`（少报 23%），
   * 而两位给 `1.23M` —— 缩写的目的是**一眼比大小**，不是把数量级之外的信息也扔掉。
   * 尾部多余的 0 由 `toLocaleString` 自己收掉（`508` 不会印成 `508.00`）。
   */
  return (value / MEGA).toLocaleString('en-US', { maximumFractionDigits: 2 }) + 'M'
}
