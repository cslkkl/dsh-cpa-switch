/**
 * 侧栏那一行的字形 —— `sidebar.panellist` 的图标（2026-10-19）。
 *
 * ## 它画的是什么
 *
 * 与插件页 `icon.svg` **同一母题**：外圈那道弧 = 同渠道里「绕着他转」的切换，
 * 中间人物 = 账号。区别只在画法：插件页是**实心蓝盘 + 反白图形**（30px 行内
 * 读得清），这里是**纯线条轮廓** —— 因为侧栏那一排官方图标（Plugins / 自动任务 /
 * 用量统计 / SSH）全是 16 格 outline，实心块插进去会显得不是一族。
 *
 * ## 几何从哪来（不要凭手感改）
 *
 * 全部由 `icon.svg` 的顶点**等比换算**，不是重新发挥。原稿 36 格：
 *
 * | 原稿                              | 本字形                               |
 * | --------------------------------- | ------------------------------------ |
 * | 弧 `M11.07 22A8 8 0 1 1 …`（r=8） | 中线 r=6.76、带宽 3.6（放大 1.25×）  |
 * | 头 `r=2.9 @ (18,16.1)`            | 圆 `r=2 @ (8.26,7.87)`               |
 * | 肩（底 y=24.4、宽 10）            | `M4.82 13.59 C…`（同一组控制点）     |
 *
 * 弧画成**带宽的轮廓**（两条同心弧 + 两端半圆端盖），也就是原稿那道粗描边的
 * 外沿与内沿 —— 与维护者给的「红描边」那张图是同一件事，只是描边改黑。
 *
 * ⚠️ **带宽是被 16px 逼出来的**：原稿带宽 2.9/36 = 1.05 格，两条 1 的描边之间
 * 只剩 0.05 格空隙 —— 等于实心（实测 16px 下就是一坨）。所以带子放大到 1.25×
 * （3.6 格），缝隙约 1.6 格，16px 下仍有可见的空档。
 * ⚠️ 端点用半圆端盖（不是尖）：维护者明确否掉了右上角那个"喙"。
 *
 * 颜色一律 `currentColor`：侧栏的选中态、明暗主题都由宿主那套 class 决定，
 * 这里不烘任何颜色。
 *
 * @module dsh-cpa-switch/client/PanelGlyph
 */

import type { ReactNode } from 'react'

/** 弧与端盖：一条闭合路径（外弧 → 端盖 → 内弧 → 端盖）。 */
const BAND =
  'M2.41 12.56A6.76 6.76 0 1 1 14.39 6.32' +
  'A1.25 1.25 0 0 1 12.12 7.37' +
  'A4.26 4.26 0 1 0 4.57 11.31' +
  'A1.25 1.25 0 0 1 2.41 12.56Z'

/** 肩（原稿那组控制点，等比换算）。 */
const SHOULDER = 'M4.82 13.59C4.82 11.95 6.68 10.55 8.26 10.55C9.85 10.55 11.71 12.14 11.71 13.59'

/**
 * 描边宽度 —— **1**，与宿主官方图标的 `Icon…OutlineRegular` 同款
 * （`Icon…OutlineMedium` 才是 1.3）。侧栏那排用的是 Regular，所以这里不能用
 * 1.3：同一行里粗一号就会显得是另一个族。
 */
const STROKE = 1

/** 侧栏那一行的图标。`size` 由宿主给（展开 18px / 折叠轨 16px）。 */
export function PanelGlyph(props: { readonly size?: number }): ReactNode {
  /** 宿主一定给 `size`；兜底 18 是为了这份组件单独渲染时不至于塌成 0。 */
  const size = props.size ?? 18
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={STROKE}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <path d={BAND} />
      <circle cx="8.26" cy="7.87" r="2" />
      <path d={SHOULDER} />
    </svg>
  )
}
